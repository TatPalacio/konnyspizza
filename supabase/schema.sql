-- Konys Pizza · Sistema de reservas · Esquema para Supabase (PostgreSQL 15+)
-- Versión 2 (auditada). Se puede ejecutar en un proyecto nuevo o sobre la
-- versión anterior: es idempotente (puede ejecutarse varias veces).
--
-- Cómo ejecutarlo: Supabase → SQL Editor → New query → pega todo → Run.
--
-- Modelo de seguridad
--   · Visitantes (rol anon): ven mesas activas, horarios y platos disponibles.
--     NO pueden leer reservas ni modificar nada. Reservan solo a través de la
--     función crear_reserva(), que valida todas las reglas en el servidor, y
--     consultan la ocupación con ocupacion_reservas(), que no expone nombres
--     ni teléfonos.
--   · Administradores: usuarios de Supabase Auth registrados en la tabla
--     public.administradores. Solo ellos leen reservas y modifican mesas,
--     horarios, platos y estados de reserva.
--   · La contraseña del panel en js/config.js NO es un mecanismo de seguridad:
--     viaja al navegador y cualquiera puede verla. Ver la sección final
--     «Panel de administración» para las opciones.
-- ==========================================================================

