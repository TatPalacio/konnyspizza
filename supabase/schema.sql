-- 0. Extensiones -----------------------------------------------------------
-- btree_gist permite combinar "misma mesa" (=) con "rangos que se cruzan" (&&)
-- en una sola restricción de exclusión.
create extension if not exists btree_gist with schema extensions;

-- 1. Tablas (sección 10 del documento) ---------------------------------------

-- 1.1 Mesas
create table if not exists public.mesas (
  id          bigint generated by default as identity primary key,
  nombre      text not null unique check (char_length(btrim(nombre)) between 1 and 30),
  zona        text not null check (zona in ('terraza', 'salon')),
  capacidad   int  not null check (capacidad between 1 and 12),
  activa      boolean not null default true,
  foto_url    text,
  creado_en   timestamptz not null default now()
);

-- 1.2 Horarios (una fila por día y jornada)
create table if not exists public.horarios (
  id            bigint generated by default as identity primary key,
  dia_semana    text not null check (dia_semana in ('lunes','martes','miércoles','jueves','viernes','sábado','domingo')),
  jornada       text not null check (jornada in ('almuerzo','noche')),
  hora_inicio   time not null,
  hora_fin      time not null,
  duracion_slot int  not null default 60 check (duracion_slot between 15 and 240),
  activo        boolean not null default true,
  constraint horarios_dia_jornada_key unique (dia_semana, jornada),
  constraint horarios_rango_check check (hora_inicio < hora_fin)
);

-- 1.3 Reservas
create table if not exists public.reservas (
  id               bigint generated by default as identity primary key,
  mesa_id          bigint not null references public.mesas(id) on delete restrict,
  cliente_nombre   text not null check (char_length(btrim(cliente_nombre)) between 3 and 80),
  cliente_contacto text check (cliente_contacto is null or cliente_contacto ~ '^[0-9]{10}$'),
  num_personas     int  not null check (num_personas >= 1),
  fecha            date not null,
  hora_inicio      time not null,
  hora_fin         time not null,
  estado           text not null default 'confirmada' check (estado in ('confirmada','cancelada','completada')),
  creado_en        timestamptz not null default now(),
  constraint reservas_rango_check check (hora_inicio < hora_fin)
);
create index if not exists reservas_fecha_idx on public.reservas (fecha);

-- 1.4 Platos
create table if not exists public.platos (
  id          bigint generated by default as identity primary key,
  nombre      text not null check (char_length(btrim(nombre)) between 1 and 60),
  categoria   text not null check (categoria in ('pizzas','entradas','postres','bebidas')),
  descripcion text not null default '' check (char_length(descripcion) <= 140),
  precio      int  not null check (precio >= 0),          -- pesos colombianos (COP)
  disponible  boolean not null default true,
  imagen      text                                         -- URL o clave de ilustración (ej. 'pizza-especial')
);

-- 1.5 Administradores (usuarios de Supabase Auth autorizados para el panel)
create table if not exists public.administradores (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  creado_en timestamptz not null default now()
);

