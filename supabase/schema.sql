-- 3. Sin reservas superpuestas (RF-05 y condición de carrera, sección 12.2) ---
-- Una mesa no puede tener dos reservas activas cuyos intervalos se crucen
-- (19:00–20:00 y 19:30–20:30 se rechazan; 19:00–20:00 y 20:00–21:00 se permiten).
-- Las canceladas no cuentan. Si al ejecutar este bloque aparece un error
-- «could not create exclusion constraint», ya existen reservas superpuestas:
-- ver la consulta de diagnóstico al final del archivo.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'reservas_sin_superposicion') then
    alter table public.reservas add constraint reservas_sin_superposicion
      exclude using gist (
        mesa_id with =,
        tsrange(fecha + hora_inicio, fecha + hora_fin, '[)') with &&
      ) where (estado <> 'cancelada');
  end if;
end $$;

-- 4. Funciones -----------------------------------------------------------------

-- 4.1 ¿El usuario actual es administrador?
create or replace function public.es_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (select 1 from public.administradores a where a.user_id = auth.uid());
$$;

-- 4.2 Integridad de reservas (se aplica también a cambios hechos por el admin).
-- Valida capacidad solo cuando cambian la mesa o el número de personas, para
-- que cancelar o completar una reserva nunca falle si después se redujo la
-- capacidad de la mesa.
create or replace function public.validar_reserva()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_cap int;
begin
  if tg_op = 'INSERT' or new.mesa_id is distinct from old.mesa_id or new.num_personas is distinct from old.num_personas then
    select m.capacidad into v_cap from public.mesas m where m.id = new.mesa_id;
    if v_cap is null then
      raise exception 'La mesa no existe.' using errcode = 'foreign_key_violation', hint = 'MESA_INACTIVA';
    end if;
    if new.num_personas > v_cap then
      raise exception 'La mesa admite máximo % personas.', v_cap using errcode = 'check_violation', hint = 'CAPACIDAD';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists reservas_validar on public.reservas;
create trigger reservas_validar
  before insert or update of mesa_id, num_personas on public.reservas
  for each row execute function public.validar_reserva();

-- 4.3 Ocupación pública: solo horarios ocupados, sin datos personales.
-- La usa el módulo cliente para pintar los slots libres y ocupados (RF-04).
create or replace function public.ocupacion_reservas(p_fecha date, p_mesa_id bigint default null)
returns table (mesa_id bigint, fecha date, hora_inicio time, hora_fin time, estado text)
language sql stable security definer
set search_path = ''
as $$
  select r.mesa_id, r.fecha, r.hora_inicio, r.hora_fin, r.estado
  from public.reservas r
  join public.mesas m on m.id = r.mesa_id and m.activa
  where r.fecha = p_fecha
    and (p_mesa_id is null or r.mesa_id = p_mesa_id)
    and r.estado <> 'cancelada'
  order by r.mesa_id, r.hora_inicio;
$$;

-- 4.4 Crear reserva (único camino de escritura para visitantes).
-- Reglas: RF-03 (día habilitado), RF-04 (slot dentro de la jornada), RF-05
-- (capacidad), RF-13 (mesa activa) y verificación final contra la
-- superposición (sección 12.2). La hora de fin la calcula el servidor con la
-- duración configurada; el cliente no puede elegirla.
-- Los errores llevan un HINT que js/supabase.js traduce a la interfaz:
-- DATOS_INVALIDOS, MESA_INACTIVA, CAPACIDAD, HORARIO_INVALIDO, HORA_OCUPADA.
create or replace function public.crear_reserva(
  p_mesa_id          bigint,
  p_fecha            date,
  p_hora_inicio      time,
  p_cliente_nombre   text,
  p_cliente_contacto text,
  p_num_personas     int
)
returns public.reservas
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_mesa     public.mesas;
  v_jornada  public.horarios;
  v_dia      text;
  v_ahora    timestamp := (now() at time zone 'America/Bogota');
  v_nombre   text := btrim(coalesce(p_cliente_nombre, ''));
  v_contacto text := nullif(regexp_replace(coalesce(p_cliente_contacto, ''), '[^0-9]', '', 'g'), '');
  v_ini      int;
  v_fin      int;
  v_res      public.reservas;
begin
  -- Datos del cliente
  if char_length(v_nombre) < 3 or char_length(v_nombre) > 80 then
    raise exception 'Ingresa tu nombre completo (3 a 80 caracteres).' using errcode = 'check_violation', hint = 'DATOS_INVALIDOS';
  end if;
  if v_contacto is not null and v_contacto !~ '^[0-9]{10}$' then
    raise exception 'Ingresa un número válido de 10 dígitos.' using errcode = 'check_violation', hint = 'DATOS_INVALIDOS';
  end if;
  if p_num_personas is null or p_num_personas < 1 then
    raise exception 'Indica cuántas personas asistirán.' using errcode = 'check_violation', hint = 'DATOS_INVALIDOS';
  end if;
  if p_fecha is null or p_hora_inicio is null then
    raise exception 'Selecciona fecha y horario.' using errcode = 'check_violation', hint = 'HORARIO_INVALIDO';
  end if;

  -- Mesa activa (bloqueo compartido: evita que la desactiven a mitad de la reserva)
  select * into v_mesa from public.mesas m where m.id = p_mesa_id for share;
  if not found or not v_mesa.activa then
    raise exception 'La mesa no está disponible para reservas.' using errcode = 'check_violation', hint = 'MESA_INACTIVA';
  end if;
  if p_num_personas > v_mesa.capacidad then
    raise exception 'La % admite máximo % personas.', v_mesa.nombre, v_mesa.capacidad using errcode = 'check_violation', hint = 'CAPACIDAD';
  end if;

  -- Día y jornada habilitados
  v_dia := (array['lunes','martes','miércoles','jueves','viernes','sábado','domingo'])[extract(isodow from p_fecha)::int];
  select * into v_jornada from public.horarios h
   where h.dia_semana = v_dia and h.activo
     and p_hora_inicio >= h.hora_inicio and p_hora_inicio < h.hora_fin
   limit 1;
  if not found then
    raise exception 'El restaurante no atiende en esa fecha u hora.' using errcode = 'check_violation', hint = 'HORARIO_INVALIDO';
  end if;
  v_ini := (extract(epoch from p_hora_inicio) / 60)::int;
  v_fin := v_ini + v_jornada.duracion_slot;
  if (v_ini - (extract(epoch from v_jornada.hora_inicio) / 60)::int) % 30 <> 0
     or v_fin > (extract(epoch from v_jornada.hora_fin) / 60)::int then
    raise exception 'Ese horario no está disponible para reservas.' using errcode = 'check_violation', hint = 'HORARIO_INVALIDO';
  end if;
  if p_fecha + p_hora_inicio <= v_ahora then
    raise exception 'Ese horario ya pasó. Elige otro.' using errcode = 'check_violation', hint = 'HORARIO_INVALIDO';
  end if;

  -- Inserción: la restricción de exclusión resuelve la condición de carrera
  begin
    insert into public.reservas (mesa_id, cliente_nombre, cliente_contacto, num_personas, fecha, hora_inicio, hora_fin, estado)
    values (v_mesa.id, v_nombre, v_contacto, p_num_personas, p_fecha, p_hora_inicio,
            make_time(v_fin / 60, v_fin % 60, 0), 'confirmada')
    returning * into v_res;
  exception when exclusion_violation then
    raise exception 'Este horario ya no está disponible.' using errcode = 'exclusion_violation', hint = 'HORA_OCUPADA';
  end;
  return v_res;
end $$;

